document.addEventListener('DOMContentLoaded', () => {
  // --- DOM Elements ---
  const header = document.getElementById('siteHeader');
  const scrollTopBtn = document.getElementById('scrollTop');
  const hamburger = document.getElementById('hamburger');
  const mainNav = document.getElementById('mainNav');
  const langToggleBtn = document.getElementById('langToggle');
  const langOptions = document.querySelectorAll('.lang-option');
  const yearSpan = document.getElementById('year');

  // --- Update Year ---
  if (yearSpan) yearSpan.textContent = new Date().getFullYear();

  // --- Scroll Effects ---
  // passive: bu isleyici asla preventDefault cagirmaz; tarayiciya bunu bildirmek
  // dokunmatik cihazlarda kaydirmanin takilmasini onler.
  window.addEventListener('scroll', () => {
    header.classList.toggle('scrolled', window.scrollY > 20);
    scrollTopBtn.classList.toggle('visible', window.scrollY > 400);
  }, { passive: true });

  scrollTopBtn.addEventListener('click', () => {
    window.scrollTo({ top: 0, behavior: 'smooth' });
  });

  // --- Seamless Video Loop (dip through the backdrop instead of a hard jump-cut) ---
  // Az hareket tercihi aciksa video CSS ile gizleniyor; gorunmeyen bir ogeye
  // saniyede 60 kez opaklik hesaplamanin anlami yok - dongu hic baslatilmaz.
  const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  const bgVideo = prefersReducedMotion ? null : document.querySelector('.site-bg-video');
  if (bgVideo) {
    const FADE = 0.6; // seconds faded at each end of the loop
    let lastOpacity = null;

    const fadeAt = (time, duration) => {
      const remaining = duration - time;
      if (remaining < FADE) return Math.max(remaining / FADE, 0);
      if (time < FADE) return Math.min(time / FADE, 1);
      return 1;
    };

    const tick = () => {
      const duration = bgVideo.duration;
      if (duration) {
        // Ayni degeri her karede yeniden yazmak bos yere stil hesaplamasi tetikler;
        // sadece deger degistiginde yaz. Gorsel sonuc birebir ayni.
        const opacity = fadeAt(bgVideo.currentTime, duration);
        if (opacity !== lastOpacity) {
          bgVideo.style.opacity = opacity;
          lastOpacity = opacity;
        }
      }
      requestAnimationFrame(tick);
    };
    requestAnimationFrame(tick);
  }

  // --- Hero Scroll Cue ---
  const scrollCue = document.getElementById('scrollCue');
  if (scrollCue) {
    scrollCue.addEventListener('click', () => {
      document.getElementById('about').scrollIntoView({ behavior: 'smooth' });
    });
  }

  // --- Mobile Menu Toggle ---
  const setMenuOpen = (isOpen) => {
    mainNav.classList.toggle('open', isOpen);
    hamburger.setAttribute('aria-expanded', String(isOpen));
  };
  setMenuOpen(false);

  hamburger.addEventListener('click', () => {
    setMenuOpen(!mainNav.classList.contains('open'));
  });

  // Close menu when clicking a link
  mainNav.querySelectorAll('a').forEach(link => {
    link.addEventListener('click', () => setMenuOpen(false));
  });

  // --- Reveal on Scroll ---
  const observerOptions = {
    root: null,
    rootMargin: '0px',
    threshold: 0.15
  };

  const observer = new IntersectionObserver((entries, observer) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('in-view');
        observer.unobserve(entry.target);
      }
    });
  }, observerOptions);

  document.querySelectorAll('section, .timeline-item, .project-card, .skill-card').forEach(el => {
    el.classList.add('reveal');
    observer.observe(el);
  });

  // --- Language State ---
  // Proje detay dugmesi de bu degiskeni okudugu icin ondan once tanimlanir.
  let currentLang = 'tr';

  // --- Project Detail Toggle ---
  document.querySelectorAll('.project-toggle').forEach(btn => {
    btn.setAttribute('aria-expanded', 'false');
    btn.addEventListener('click', () => {
      const card = btn.closest('.project-card');
      const isOpen = card.classList.toggle('is-open');
      const key = isOpen ? 'projects.toggle.hide' : 'projects.toggle.show';
      btn.setAttribute('aria-expanded', String(isOpen));
      btn.setAttribute('data-i18n', key);
      btn.textContent = translations[currentLang][key];
    });
  });

  // --- Language Toggle ---
  function updateLanguage(lang) {
    if (lang === currentLang) return;
    currentLang = lang;
    
    // Update <html lang> for SEO & accessibility
    document.documentElement.lang = lang;

    // Update Toggle Buttons UI
    langOptions.forEach(opt => {
      opt.classList.toggle('active', opt.dataset.lang === lang);
    });

    // Update Text Content
    // textContent kullaniliyor: tum ceviriler duz metin oldugu icin render sonucu
    // innerHTML ile birebir ayni, ancak HTML enjeksiyon yuzeyi tamamen ortadan kalkiyor.
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (translations[lang] && translations[lang][key]) {
        el.textContent = translations[lang][key];
      }
    });

    // Update aria-label Content
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const key = el.getAttribute('data-i18n-aria');
      if (translations[lang] && translations[lang][key]) {
        el.setAttribute('aria-label', translations[lang][key]);
      }
    });
  }

  langToggleBtn.addEventListener('click', (e) => {
    // If user clicked directly on one of the span options
    if (e.target.classList.contains('lang-option')) {
      updateLanguage(e.target.dataset.lang);
    } else {
      // Toggle between TR and EN
      updateLanguage(currentLang === 'tr' ? 'en' : 'tr');
    }
  });
});
